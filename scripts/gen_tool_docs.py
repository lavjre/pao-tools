"""Generate the tool inventory table (docs/tool-reference/index.mdx fragment).

Usage:
    uv run python scripts/gen_tool_docs.py [--check]

Default writes ``docs/tool-reference/generated-tools.mdx`` from the live
``create_mcp()`` registry so docs never drift from the 212-tool contract.
``--check`` exits nonzero when the file is stale (CI docs gate).
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "tool-reference" / "generated-tools.mdx"


async def _inventory() -> list[tuple[str, str]]:
    from paomcp.server import create_mcp

    mcp = create_mcp()
    tools = await mcp.list_tools(run_middleware=False)
    rows = []
    for tool in sorted(tools, key=lambda t: t.name):
        first_line = (tool.description or "").strip().splitlines()
        rows.append((tool.name, first_line[0] if first_line else ""))
    return rows


def render(rows: list[tuple[str, str]]) -> str:
    lines = [
        "---",
        'title: "Generated tool inventory"',
        'description: "Auto-generated MCP tool list. Do not edit by hand."',
        "---",
        "",
        "> Auto-generated by `uv run python scripts/gen_tool_docs.py`.",
        "",
        f"Total tools: **{len(rows)}**.",
        "",
        "| Tool | Summary |",
        "|------|---------|",
    ]
    for name, summary in rows:
        summary = summary.replace("|", "\\|").strip()
        lines.append(f"| `{name}` | {summary} |")
    lines.append("")
    return "\n".join(lines)


async def main(check: bool) -> int:
    rows = await _inventory()
    text = render(rows)
    if check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT} (run uv run python scripts/gen_tool_docs.py)")
            return 1
        print(f"ok: {OUT} ({len(rows)} tools)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main("--check" in sys.argv[1:])))
